// Turning a nest into something the exporters can draw.
//
// There are two nesters -- the bounding-box one the page runs, and the
// true-shape one that works from CAD outlines -- and they hold their results
// differently. Both end up here, so the PDF and the DXF are produced by one
// code path and cannot drift apart.

import type { CutPlanDocument, CutPlanLoop, CutPlanPiece, CutPlanSheet, Pt } from "./cutPlanExport";
import type { NestResult } from "./nesting";
import { checkClearances } from "./clearanceCheck";

// The outlines the page carries are SVG path strings, because that is what the
// browser draws. They are generated by our own extraction and only ever
// contain move/line/close -- curves were flattened long before this point --
// so this reads exactly that and nothing else. Anything it does not understand
// is dropped rather than guessed at: a mis-parsed contour is a wrong cut.
export function parseSvgPathLoops(d: string): Pt[][] {
  const loops: Pt[][] = [];
  let current: Pt[] = [];
  // Commands, then the numbers that follow them.
  const tokens = d.match(/[MmLlZzHhVv]|-?\d*\.?\d+(?:[eE][-+]?\d+)?/g);
  if (!tokens) return loops;

  let cmd = "";
  let i = 0;
  let x = 0;
  let y = 0;
  const num = () => Number(tokens[i++]);
  const flush = () => {
    if (current.length >= 3) loops.push(current);
    current = [];
  };

  while (i < tokens.length) {
    const token = tokens[i];
    if (/[MmLlZzHhVv]/.test(token)) {
      cmd = token;
      i++;
      if (cmd === "Z" || cmd === "z") {
        flush();
        continue;
      }
      if (cmd === "M" || cmd === "m") flush();
    }
    // A bare number after M continues as an implicit L, which is how a
    // polyline written "M x y L x y x y" is meant to read.
    switch (cmd) {
      case "M":
      case "L":
        x = num();
        y = num();
        break;
      case "m":
      case "l":
        x += num();
        y += num();
        break;
      case "H":
        x = num();
        break;
      case "h":
        x += num();
        break;
      case "V":
        y = num();
        break;
      case "v":
        y += num();
        break;
      default:
        // Unrecognised command: stop rather than emit geometry we did not read.
        return loops;
    }
    current.push([x, y]);
    if (cmd === "M") cmd = "L";
    if (cmd === "m") cmd = "l";
  }
  flush();
  return loops;
}

function ellipseLoop(w: number, h: number, segments = 72): Pt[] {
  const pts: Pt[] = [];
  for (let i = 0; i < segments; i++) {
    const a = (i / segments) * Math.PI * 2;
    pts.push([w / 2 + (w / 2) * Math.cos(a), h / 2 + (h / 2) * Math.sin(a)]);
  }
  return pts;
}

function boxLoop(w: number, h: number): Pt[] {
  return [
    [0, 0],
    [w, 0],
    [w, h],
    [0, h],
  ];
}

// A placement's outline lives in the part's own unrotated frame. When the
// packer turned the piece 90 degrees the box was turned with it but the path
// was not, so it has to be turned here or the profile sits crosswise in its
// own box.
function rotate90(points: Pt[], newW: number): Pt[] {
  return points.map(([x, y]) => [newW - y, x] as Pt);
}

export interface CutPlanMeta {
  title: string;
  subtitle: string;
  extraNotes?: string[];
}

/**
 * The page's own nest, ready to export. Where a part has a real outline it is
 * drawn; where it does not -- which is every part read from a plotted PDF
 * rather than from CAD -- the bounding box is drawn instead, and the notes say
 * so, because a rectangle presented as a contour is the one mistake on this
 * drawing that would reach the torch.
 */
export function nestResultToCutPlan(nest: NestResult, meta: CutPlanMeta): CutPlanDocument {
  // Colour by part, not by placement, so four copies of one part read as one
  // part -- matching the screen.
  const colourIndex = new Map<string, number>();
  for (const plate of nest.plates) {
    for (const pl of plate.placements) {
      if (!colourIndex.has(pl.partId)) colourIndex.set(pl.partId, colourIndex.size);
    }
  }

  let outlined = 0;
  let boxed = 0;

  const sheets: CutPlanSheet[] = nest.plates.map((plate) => ({
    index: plate.index,
    lengthMm: plate.lengthMm,
    widthMm: plate.widthMm,
    thicknessMm: plate.thicknessMm,
    material: plate.material,
    kerfMm: plate.allowances.kerfMm,
    spacingMm: plate.allowances.spacingMm,
    edgeMarginMm: plate.allowances.edgeMarginMm,
    // Deliberately not drawn. The box nester reports the largest free
    // rectangle as a SIZE with no position -- it is an estimate of what can go
    // back on the rack, not a located strip -- so drawing it as a band at the
    // far end of the plate would put a rectangle on the plan that is not
    // where the metal is. It is stated in the notes instead.
    remnant: null,
    pieces: plate.placements.map((pl): CutPlanPiece => {
      let loops: CutPlanLoop[] = [];
      // Loops carried from the CAD read: which ones close and which are holes
      // is recorded there, and it cannot be recovered from the outline. Using
      // them beats parsing the path back and guessing.
      if (pl.outlineLoops?.length) {
        outlined++;
        loops = pl.outlineLoops.map((loop) => ({ points: loop.points, closed: loop.closed, hole: loop.hole }));
      } else if (pl.outlinePath) {
        const raw = parseSvgPathLoops(pl.outlinePath);
        if (raw.length) {
          outlined++;
          // The path is in the part's drawn frame; the box may have been turned.
          const turned = pl.rotated ? raw.map((loop) => rotate90(loop, pl.w)) : raw;
          // The largest loop is the profile, the rest are cut-outs inside it.
          const areas = turned.map(loopArea);
          const biggest = areas.indexOf(Math.max(...areas));
          loops = turned.map((points, i) => ({ points, closed: true, hole: i !== biggest }));
        }
      }
      if (!loops.length) {
        boxed++;
        loops = [
          {
            points: pl.shape === "circle" ? ellipseLoop(pl.w, pl.h) : boxLoop(pl.w, pl.h),
            closed: true,
            hole: false,
          },
        ];
      }
      return {
        partNo: pl.partNo,
        instance: pl.instance,
        xMm: pl.x,
        yMm: pl.y,
        wMm: pl.w,
        hMm: pl.h,
        // A true-shape nest turns parts by arbitrary angles and reports the
        // real one; a box nest can only say "turned" and means 90.
        rotationDeg: pl.rotationDeg ?? (pl.rotated ? 90 : 0),
        loops,
        colourIndex: colourIndex.get(pl.partId) ?? 0,
      };
    }),
  }));

  const notes: string[] = [];
  const plan = nest.allowancePlans[0];
  if (plan) {
    notes.push(
      `Cutting allowances: ${plan.allowances.spacingMm} mm between parts (${plan.allowances.kerfMm} mm kerf + ` +
        `${plan.allowances.webMm} mm web) and ${plan.allowances.edgeMarginMm} mm off the rolled edge. ${plan.basis}`
    );
  }
  if (boxed > 0) {
    notes.push(
      outlined > 0
        ? `${boxed} of ${boxed + outlined} pieces are drawn as their BOUNDING BOX, not their profile -- the drawing they came from ` +
          `carries no outline. Those rectangles are the space reserved, not the cut line; cut them to the dimensioned figures.`
        : `Every piece is drawn as its BOUNDING BOX, not its profile: the source drawing carries dimensions but no outline geometry. ` +
          `The rectangles are the space each part reserves and the positions are real, but the cut line is not -- take the shape from ` +
          `the part drawing. Nest from the CAD file to get true contours.`
    );
  }
  if (nest.unplaced.length > 0) {
    const total = nest.unplaced.reduce((sum, u) => sum + u.quantity, 0);
    notes.push(
      `NOT ON THESE PLATES: ${total} piece(s) -- ` +
        nest.unplaced.map((u) => `${u.part.partNo} x ${u.quantity}`).join(", ") +
        `. ${nest.unplaced[0].reason}`
    );
  }
  // The allowance is the point of the plan, so the plan carries its own proof
  // of it -- measured on the finished polygons, not on the raster the nester
  // used to place them.
  const clearance = checkClearances(nest);
  if (clearance.plates.length > 0) {
    notes.push(
      clearance.ok
        ? `CLEARANCE CHECKED on the finished outlines: the tightest gap anywhere on this plan is ${clearance.minGapMm} mm against the ` +
          `${clearance.plates[0].requiredGapMm} mm required, and the closest approach to a plate edge is ${clearance.minEdgeMm} mm ` +
          `against ${clearance.plates[0].requiredEdgeMm} mm. Every piece has its full kerf and web, so every piece cuts to size.`
        : `CLEARANCE WARNING: ${clearance.violations.length} place(s) are tighter than the allowance. Tightest gap ${clearance.minGapMm} mm ` +
          `against ${clearance.plates[0].requiredGapMm} mm required` +
          clearance.violations
            .slice(0, 4)
            .map((v) => ` -- ${v.a} to ${v.b} at ${v.actualMm} mm`)
            .join("") +
          `. Those pieces may cut undersized.`
    );
  }

  const offcuts = nest.plates
    .filter((plate) => plate.largestOffcut)
    .map((plate) => `plate ${plate.index}: approx. ${plate.largestOffcut!.lengthMm} x ${plate.largestOffcut!.widthMm} mm`);
  if (offcuts.length) {
    notes.push(
      `Largest usable offcut -- ${offcuts.join("; ")}. Measured off the packer's free space with the cutting spacing taken back off, ` +
        `so it is a figure to reach for a tape with, not one to cut to, and it is not drawn on the layout because its position is not fixed.`
    );
  }
  notes.push(
    `Positions are the top-left corner of each part's bounding box measured from the plate's top-left corner. ` +
      `Utilisation is measured on bounding boxes, so a part with an irregular profile uses less metal than the figure shows.`
  );
  for (const note of meta.extraNotes ?? []) notes.push(note);

  const partSeen = new Map<string, { partNo: string; sizeMm: string; quantity: number; note: string; colourIndex: number }>();
  for (const plate of nest.plates) {
    for (const pl of plate.placements) {
      const existing = partSeen.get(pl.partId);
      if (existing) {
        existing.quantity += 1;
        continue;
      }
      partSeen.set(pl.partId, {
        partNo: pl.partNo,
        sizeMm: `${Math.round(pl.rotated ? pl.h : pl.w)} x ${Math.round(pl.rotated ? pl.w : pl.h)}`,
        quantity: 1,
        note: pl.outlineLoops?.length || pl.outlinePath ? "true profile" : "bounding box only",
        colourIndex: colourIndex.get(pl.partId) ?? 0,
      });
    }
  }

  // Derived from the placements themselves, so any change to the layout gives
  // a different id and two files that agree can be trusted to agree.
  let hash = 2166136261;
  for (const sheet of sheets) {
    for (const piece of sheet.pieces) {
      for (const ch of `${piece.partNo}${piece.instance}${Math.round(piece.xMm)},${Math.round(piece.yMm)},${piece.rotationDeg}`) {
        hash ^= ch.charCodeAt(0);
        hash = Math.imul(hash, 16777619);
      }
    }
    for (const ch of `${sheet.lengthMm}x${sheet.widthMm}x${sheet.thicknessMm}g${sheet.spacingMm}e${sheet.edgeMarginMm}`) {
      hash ^= ch.charCodeAt(0);
      hash = Math.imul(hash, 16777619);
    }
  }
  const planId = (hash >>> 0).toString(36).toUpperCase().slice(0, 6);

  return {
    title: meta.title,
    subtitle: meta.subtitle,
    planId,
    stats: [
      { label: "Plates used", value: String(nest.totals.plateCount) },
      { label: "Plate bought", value: `${nest.totals.plateAreaM2.toFixed(2)} m2` },
      { label: "Taken by parts", value: `${nest.totals.partAreaM2.toFixed(2)} m2` },
      { label: "Waste", value: `${nest.totals.wasteM2.toFixed(2)} m2` },
      { label: "Utilisation", value: `${(nest.totals.utilisation * 100).toFixed(1)} %` },
      { label: "Pieces", value: String(nest.plates.reduce((sum, p) => sum + p.placements.length, 0)) },
    ],
    notes,
    sheets,
    partList: [...partSeen.values()],
  };
}

function loopArea(points: Pt[]): number {
  let sum = 0;
  for (let i = 0; i < points.length; i++) {
    const a = points[i];
    const b = points[(i + 1) % points.length];
    sum += a[0] * b[1] - b[0] * a[1];
  }
  return Math.abs(sum) / 2;
}
