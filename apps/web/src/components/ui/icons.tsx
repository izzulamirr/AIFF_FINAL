// A small stroke-icon set, drawn on a 24px grid at one weight so every icon in
// the app reads as the same family. Inline rather than a package: it is a
// dozen shapes, and it keeps the dependency list unchanged.
//
// Sized with the `size` prop (default 18) and coloured with `currentColor`, so
// an icon takes whatever text colour its parent has.
type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & { size?: number };

function Svg({ size = 18, children, ...rest }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

